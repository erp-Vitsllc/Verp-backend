import mongoose from 'mongoose';

const workOrderSchema = new mongoose.Schema(
    {
        workOrderNo: { type: String, required: true, unique: true, immutable: true },
        createdOn: { type: String, required: true, immutable: true },
        year: { type: Number, required: true, immutable: true },
        sequence: { type: Number, required: true, immutable: true },
        customer: { type: String, required: true, trim: true },
        customerId: { type: String, default: '' },
        vendorId: { type: String, default: '' },
        vendorName: { type: String, default: '', trim: true },
        quotationRef: { type: String, default: '', trim: true },
        quotationId: { type: String, default: '', trim: true },
        quotationDate: { type: String, default: '' },
        quotationSnapshot: { type: mongoose.Schema.Types.Mixed, default: null },
        quotationFile: {
            name: { type: String, default: '' },
            mime: { type: String, default: '' },
            data: { type: String, default: '' },
            bytes: { type: Number, default: 0 },
        },
        budgeted: { type: Boolean, default: false },
        budgets: {
            type: [
                {
                    revision: { type: Number, default: 1 },
                    savedAt: { type: Date, default: Date.now },
                    savedByName: { type: String, default: '' },
                    action: { type: String, enum: ['convert', 'rebudget', 'resync'], default: 'convert' },
                    quote: { type: mongoose.Schema.Types.Mixed, default: {} },
                },
            ],
            default: [],
        },
        valueExclVat: { type: Number, default: 0, min: 0 },
        vatAmount: { type: Number, default: 0, min: 0 },
        lpoNo: { type: String, default: '', trim: true },
        confirmationDate: { type: String, default: '' },
        location: { type: String, default: '', trim: true },
        description: { type: String, default: '', trim: true },
        salespersonId: { type: String, default: '' },
        salespersonEmployeeId: { type: String, default: '' },
        salespersonName: { type: String, default: '', trim: true },
        draftForEmployeeIds: { type: [String], default: [] },
        lpoMode: {
            type: String,
            enum: ['required', 'not_required', 'received'],
            default: 'required',
        },
        lpos: {
            type: [
                {
                    lpoNo: { type: String, default: '', trim: true },
                    lpoDate: { type: String, default: '' },
                    lpoValue: { type: Number, default: 0, min: 0 },
                    attachmentName: { type: String, default: '' },
                    attachmentMime: { type: String, default: '' },
                    attachmentData: { type: String, default: '' },
                    attachmentBytes: { type: Number, default: 0 },
                },
            ],
            default: [],
        },
        lpoFollowUp: {
            type: String,
            enum: ['', 'salesperson', 'coordinator'],
            default: '',
        },
        supportingNote: { type: String, default: '', trim: true },
        supportingDocument: {
            name: { type: String, default: '' },
            mime: { type: String, default: '' },
            data: { type: String, default: '' },
            bytes: { type: Number, default: 0 },
        },
        attachmentPending: { type: Boolean, default: false },
        lpoLocked: { type: Boolean, default: false },
        actualBoq: {
            status: { type: String, enum: ['', 'draft', 'pending', 'approved', 'rejected'], default: '' },
            tables: { type: [mongoose.Schema.Types.Mixed], default: [] },
            requestedByName: { type: String, default: '' },
            requestedById: { type: String, default: '' },
            requestedAt: { type: Date },
            reason: { type: String, default: '' },
            decidedByName: { type: String, default: '' },
            decidedAt: { type: Date },
        },
        materialRequest: {
            status: { type: String, enum: ['', 'open'], default: '' },
            createdAt: { type: Date },
            purchaserName: { type: String, default: '' },
            purchaserId: { type: String, default: '' },
            tables: { type: [mongoose.Schema.Types.Mixed], default: [] },
        },
        lpoApproval: {
            status: { type: String, enum: ['', 'draft', 'pending', 'rejected'], default: '' },
            mode: { type: String, enum: ['', 'required', 'not_required', 'received'], default: '' },
            note: { type: String, default: '' },
            reason: { type: String, default: '' },
            requestedByName: { type: String, default: '' },
            requestedById: { type: String, default: '' },
            requestedAt: { type: Date },
            lpoNo: { type: String, default: '' },
            lpoDate: { type: String, default: '' },
            lpoValue: { type: Number, default: 0 },
            attachmentName: { type: String, default: '' },
            attachmentMime: { type: String, default: '' },
            attachmentData: { type: String, default: '' },
            attachmentBytes: { type: Number, default: 0 },
        },
        lpoAlert: {
            active: { type: Boolean, default: false },
            kind: { type: String, default: '' },
            message: { type: String, default: '' },
            sentAt: { type: Date },
            sentByName: { type: String, default: '' },
            sentById: { type: String, default: '' },
            attachmentName: { type: String, default: '' },
            attachmentMime: { type: String, default: '' },
            attachmentData: { type: String, default: '' },
            attachmentBytes: { type: Number, default: 0 },
            emailed: { type: Boolean, default: false },
            emailTo: { type: String, default: '' },
            forEmployeeIds: { type: [String], default: [] },
        },
        status: {
            type: String,
            enum: ['Draft', 'Not Started', 'Awaiting LPO', 'LPO Pending', 'Created', 'In Progress', 'Fully Invoiced', 'Completed'],
            default: 'Draft',
        },
        type: {
            type: String,
            enum: ['Standalone', 'Main WO', 'Variation'],
            default: 'Standalone',
        },
        value: { type: Number, default: 0, min: 0 },
        invoicedAmount: { type: Number, default: 0, min: 0 },
        invoices: {
            type: [
                {
                    invoiceNo: { type: String, default: '', trim: true },
                    invoiceDate: { type: String, default: '' },
                    value: { type: Number, default: 0, min: 0 },
                },
            ],
            default: [],
        },
        projectName: { type: String, default: '', trim: true },
        createdBy: { type: String, default: '' },
        createdByName: { type: String, default: '' },
        oldDocuments: {
            type: [
                {
                    name: { type: String, default: '' },
                    mime: { type: String, default: '' },
                    data: { type: String, default: '' },
                    bytes: { type: Number, default: 0 },
                    kind: { type: String, default: '' },
                    fromStatus: { type: String, default: '' },
                    fromLpoMode: { type: String, default: '' },
                    note: { type: String, default: '' },
                    reason: { type: String, default: '' },
                    replacedAt: { type: Date },
                    replacedByName: { type: String, default: '' },
                    archiveSignature: { type: String, default: '' },
                },
            ],
            default: [],
        },
    },
    { timestamps: true },
);

workOrderSchema.index({ year: 1, sequence: 1 }, { unique: true });

export default mongoose.model('WorkOrder', workOrderSchema);
